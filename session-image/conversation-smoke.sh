#!/bin/bash
# ──────────────────────────────────────────────────────────────────────────────
# Conversation-hooks smoke test (Phase 3.0c, docs/CONVERSATION.md §10 "3.0c").
#
# Runs the REAL `claude` of the built image inside a session container set up
# the way DockerManager sets one up (hardened run flags, SESSION_ID, the
# managed-settings directory bind-mounted read-only, ST_INGEST_TOKEN and
# ST_BACKEND_PORT only when capture is on), on a private Docker network where
# `st-backend` is a real network alias, exactly like `sessions-net` in
# docker-compose.yml. The hooks go to the image's loopback relay (§2.6), which
# forwards to st-backend: the CLI refuses HTTP hooks to private addresses.
#
# What stands in for production:
#   - the model: session-image/test/mock-anthropic.mjs (ANTHROPIC_BASE_URL),
#     a scripted Messages API — no API key, no egress, no cost;
#   - the backend: session-image/test/st-receiver.mts, the real 3.0b ingest
#     stack (handler + service + store) with only D1 emulated; or
#     session-image/test/recorder.mjs where a misbehaving backend (hang, 500,
#     non-JSON, redirect, slow) or a proxy is the point;
#   - the hooks file: generated by the backend's own buildHooksSettings(), so
#     this test can't drift from what the backend writes, and written
#     root-owned (0755 dir / 0644 file) as the backend does;
#   - the proxy env: computed by the backend's own withRelayNoProxy();
#   - the emergency command: the real `conversation:disable` CLI, in another
#     process, against the same host directory.
#
# Phases:
#   0  compose: `app` carries the `st-backend` alias on sessions-net
#   1  image: empty managed dir, script and relay root-owned, CLI pin
#   2  capture off (no mount / token without file / empty mount): zero
#      requests, no relay process, port closed; baselines
#   3  capture on, real backend: relay on loopback only, contract events
#      persisted with identifiers, tools, subagents, end events, coexistence
#      with the user's own hooks, PermissionRequest still prompts the user;
#      streaming cost (MessageDisplay) against the baseline
#   4  backend absent (DNS), refused, hung, unexpected answers: agent results
#      and timings unchanged, no hook error on screen; on recovery the losses
#      are persisted as `gap relay_dropped` with the relay's exact count
#   5  script and CLI faults: script ≤ 6 s in every failure mode (relay
#      absent or hung, `claude --version` hung), relay hung under the CLI,
#      `claude --version` failing or hanging, the script missing
#   6  relay killed: restarted by its supervisor, `gap relay_restart`; relay
#      and supervisor killed: Claude keeps working
#   7  saturation: bounded queue, losses counted end to end; relay latency,
#      CPU and memory measured
#   8  HTTP_PROXY/NO_PROXY: with the backend's NO_PROXY the hooks stay local;
#      a user proxy without it only loses capture
#   9  container restart and recreate: capture follows mount + env only; the
#      token never lands in the workspace
#   10 deactivation (file removed) and revocation (real CLI): ingest cut at
#      once, next session silent; hot reload of a running session measured
#
# A markdown summary of every measurement is printed at the end and, in CI,
# appended to $GITHUB_STEP_SUMMARY.
#
# Usage: ./session-image/conversation-smoke.sh [image-tag]
# Dependencies: docker (with compose), node + backend deps (`npm ci` in
# backend/), jq.
# ──────────────────────────────────────────────────────────────────────────────
set -uo pipefail

IMAGE="${1:-shared-terminal-session}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUF="$$"
NET="st-conv-net-$SUF"
API="st-conv-api-$SUF"
RECV="st-conv-recv-$SUF"
PROXY="st-conv-proxy-$SUF"
SESS="st-conv-sess-$SUF"
TMP="$(mktemp -d)"
WS="$TMP/ws"          # the session's workspace bind mount
WR="$TMP/wr"          # the receiver's WORKSPACE_ROOT (host side)
OUT="$TMP/out"        # raw request logs written by the stand-ins
EMPTY="$TMP/empty"    # an empty directory to mount over things
mkdir -p "$WS" "$WR" "$OUT" "$EMPTY"
chmod 777 "$WS" "$OUT"
SID="$(cat /proc/sys/kernel/random/uuid)"
TOKEN="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
API_KEY="sk-ant-api03-smoke-$(head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')"
MANAGED="$WR/.claude-managed/$SID"
RELAY_PORT=47613
RELAY_DEBUG=(-e ST_HOOKS_DEBUG=1 -e ST_RELAY_STATS_INTERVAL=0.2)
FAILS=0
SUMMARY="$TMP/summary.md"
: >"$SUMMARY"

cleanup() {
	docker rm -f "$API" "$RECV" "$PROXY" "$SESS" >/dev/null 2>&1
	docker network rm "$NET" >/dev/null 2>&1
	# Root- and uid-1000-owned files from the containers: empty the dirs
	# from a throwaway root container, then drop them.
	docker run --rm --user 0 -v "$TMP":/t --entrypoint bash "$IMAGE" \
		-c 'rm -rf /t/* /t/.[!.]* 2>/dev/null; true' >/dev/null 2>&1
	rm -rf "$TMP" 2>/dev/null
}
trap cleanup EXIT

phase() { echo; echo "── $1 ──"; echo >>"$SUMMARY"; echo "**$1**" >>"$SUMMARY"; echo >>"$SUMMARY"; }
ok() { echo "  ok: $1"; }
fail() {
	echo "  FAIL: $1" >&2
	echo "- FAIL: $1" >>"$SUMMARY"
	FAILS=$((FAILS + 1))
}
check() { # check <description> <command...>
	local what="$1"
	shift
	if "$@"; then ok "$what"; else fail "$what"; fi
}
note() { echo "  · $1"; echo "- $1" >>"$SUMMARY"; }
ms_now() { echo $(($(date +%s%N) / 1000000)); }
median3() { printf '%s\n' "$@" | sort -n | sed -n 2p; }

# Root-side view of the receiver's host directory (files there are owned by
# root, as the backend's are).
as_root() { docker run --rm --user 0 -v "$WR":/wr -v "$OUT":/out --entrypoint bash "$IMAGE" -c "$1"; }

# ── Stand-ins ───────────────────────────────────────────────────────────────
start_api() {
	docker run -d --name "$API" --network "$NET" --network-alias mock-api \
		-v "$REPO_ROOT/session-image/test":/t:ro -v "$OUT":/out \
		--entrypoint node "$IMAGE" /t/mock-anthropic.mjs 8080 /out/model-requests.jsonl >/dev/null
	wait_log "$API" "listening"
}

wait_log() { # wait_log <container> <text>
	local i=0
	until docker logs "$1" 2>&1 | grep -q "$2"; do
		i=$((i + 1))
		if [ "$i" -gt 120 ]; then
			fail "$1 never logged '$2'"
			docker logs "$1" 2>&1 | tail -20 >&2
			return 1
		fi
		sleep 0.5
	done
}

# receiver <kind> <tag>: kind = real | ok | hang | status500 | text200 |
# json200-invalid | redirect | slow:<ms> | refused | none. Every kind but
# `none` owns the `st-backend` alias; requests land in $OUT/<tag>.jsonl
# (appended, so the same tag can span a receiver restart). The previous one
# is stopped gracefully first, so the real receiver flushes its store.
receiver() {
	docker stop -t 5 "$RECV" >/dev/null 2>&1
	docker rm -f "$RECV" >/dev/null 2>&1
	local kind="$1" tag="$2"
	case "$kind" in
	none) return 0 ;;
	refused)
		# The name resolves, nothing listens on 3001.
		docker run -d --name "$RECV" --network "$NET" --network-alias st-backend \
			--entrypoint sleep "$IMAGE" infinity >/dev/null
		return 0
		;;
	real)
		docker run -d --name "$RECV" --network "$NET" --network-alias st-backend --user 0 \
			-v "$REPO_ROOT":/repo:ro -v "$WR":/wr -v "$OUT":/out -w /repo/backend \
			-e WORKSPACE_ROOT=/wr -e ST_TEST_TOKEN="$TOKEN" -e ST_TEST_SESSION="$SID" \
			-e RAW_OUT="/out/$tag.jsonl" \
			--entrypoint node "$IMAGE" node_modules/tsx/dist/cli.mjs ../session-image/test/st-receiver.mts >/dev/null
		;;
	*)
		docker run -d --name "$RECV" --network "$NET" --network-alias st-backend --user 0 \
			-v "$REPO_ROOT/session-image/test":/t:ro -v "$OUT":/out \
			--entrypoint node "$IMAGE" /t/recorder.mjs "$kind" 3001 "/out/$tag.jsonl" >/dev/null
		;;
	esac
	wait_log "$RECV" "listening"
}

count() { # count <tag> [jq filter]: requests a stand-in received
	local f="$OUT/$1.jsonl"
	[ -f "$f" ] || { echo 0; return; }
	jq -s "map(select(${2:-true})) | length" "$f"
}

# Persisted events of one conversation, one compact JSON per line.
conv_events() { as_root "cat /wr/.conversations/$SID/$1.events.jsonl 2>/dev/null"; }
# Claude session_id of the latest UserPromptSubmit whose prompt is $2 in tag $1.
cid_of() { jq -r --arg p "$2" 'select(.event == "UserPromptSubmit" and .body.prompt == $p) | .body.session_id' "$OUT/$1.jsonl" 2>/dev/null | tail -n 1; }
# gaps and prompts of a conversation in order, e.g. "prompt:a relay_dropped prompt:b".
conv_order() {
	conv_events "$1" | jq -r 'if .ev == "gap" then .data.reason elif .ev == "user_prompt" then "prompt:" + .data.prompt else empty end' | tr '\n' ' '
}

# ── Hooks file (host side, root-owned like the backend's) ──────────────────
# To a file, not a variable: `$(…)` would strip the trailing newline and the
# copy would no longer be byte-identical to what the backend writes.
HOOKS_FILE="$TMP/conversation.json"
(cd "$REPO_ROOT/backend" && npx tsx -e \
	'import { buildHooksSettings } from "./src/conversation/activation.ts"; process.stdout.write(buildHooksSettings())') >"$HOOKS_FILE" ||
	{ fail "couldn't generate the hooks file from activation.ts"; exit 1; }
write_hooks_file() { # atomic, like writeHooksFile(): temp name the CLI ignores, then rename
	docker run --rm -i --user 0 -v "$WR":/wr --entrypoint bash "$IMAGE" -c "
		install -d -m 0755 /wr/.claude-managed /wr/.claude-managed/$SID &&
		cat > /wr/.claude-managed/$SID/conversation.json.tmp.1 &&
		chmod 0644 /wr/.claude-managed/$SID/conversation.json.tmp.1 &&
		mv /wr/.claude-managed/$SID/conversation.json.tmp.1 /wr/.claude-managed/$SID/conversation.json" <"$HOOKS_FILE"
}
remove_hooks_file() { as_root "rm -f /wr/.claude-managed/$SID/conversation.json"; }

# ── Session container ───────────────────────────────────────────────────────
# session <with-token: yes|no> <managed: file|empty|none> [extra docker args…]
# Flags mirror DockerManager.spawn(): init, all caps dropped,
# no-new-privileges, SESSION_ID always, the token and the backend port only
# when capture is on (prepareSpawnCapture).
session() {
	local tok="$1" managed="$2"
	shift 2
	docker rm -f "$SESS" >/dev/null 2>&1
	local args=(--init --cap-drop ALL --security-opt no-new-privileges --pids-limit 512
		--network "$NET" -e SESSION_ID="$SID" -e SESSION_NAME=smoke
		-e ANTHROPIC_BASE_URL=http://mock-api:8080 -e ANTHROPIC_API_KEY="$API_KEY"
		-e CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1
		-v "$WS":/home/developer/workspace)
	[ "$tok" = yes ] && args+=(-e ST_INGEST_TOKEN="$TOKEN" -e ST_BACKEND_PORT=3001)
	case "$managed" in
	file) args+=(-v "$MANAGED":/etc/claude-code/managed-settings.d:ro) ;;
	empty) args+=(-v "$EMPTY":/etc/claude-code/managed-settings.d:ro) ;;
	esac
	docker run -d --name "$SESS" "${args[@]}" "$@" "$IMAGE" >/dev/null || {
		fail "docker run of the session container failed"
		return 1
	}
	wait_log "$SESS" "container ready" || return 1
	seed_claude_state
}

# Interactive-mode prerequisites the first launch would otherwise ask for
# (onboarding, API-key approval, workspace trust, bypass-mode warning), plus
# the user's OWN hooks — a command UserPromptSubmit/Stop pair writing to
# /tmp/user-hooks.log — so every phase also proves managed hooks coexist with
# them. Written through the ~/.claude* symlinks into the workspace.
seed_claude_state() {
	docker exec -i -e K="${API_KEY: -20}" "$SESS" bash -c '
		set -e
		f=~/.claude.json; [ -s "$f" ] || echo "{}" > "$f"
		jq --arg k "$K" ". + {hasCompletedOnboarding: true, theme: \"dark\",
			customApiKeyResponses: {approved: [\$k], rejected: []},
			projects: {\"/home/developer/workspace\": {hasTrustDialogAccepted: true, hasCompletedProjectOnboarding: true}}}" "$f" > /tmp/cj
		cat /tmp/cj > "$f"
		mkdir -p ~/.claude
		cat > ~/.claude/settings.json <<"EOF"
{
  "skipDangerousModePermissionPrompt": true,
  "hooks": {
    "UserPromptSubmit": [{ "hooks": [{ "type": "command", "command": "echo submit $(date +%s%3N) >> /tmp/user-hooks.log" }] }],
    "Stop": [{ "hooks": [{ "type": "command", "command": "echo stop $(date +%s%3N) >> /tmp/user-hooks.log" }] }]
  }
}
EOF'
}

# ── Relay probes (inside the session container) ─────────────────────────────
# relay_pids: pid of every `python3 -IS /opt/st/hooks/relay.py` process.
relay_pids() {
	docker exec "$SESS" bash -c 'for p in /proc/[0-9]*; do
		c=$(tr "\0" " " <"$p/cmdline" 2>/dev/null)
		case "$c" in "python3 -IS /opt/st/hooks/relay.py"*) echo "${p#/proc/}" ;; esac
	done' 2>/dev/null
}
relay_count() { relay_pids | grep -c .; }
relay_listening() { docker exec "$SESS" bash -c "(exec 3<>/dev/tcp/127.0.0.1/$RELAY_PORT) 2>/dev/null"; }
relay_closed() { ! relay_listening; }
# relay_stat <counter>: latest value from the relay's debug line (0 if absent).
relay_stat() {
	docker exec "$SESS" bash -c 'grep "^st-relay [a-z_]*=" /tmp/st-relay.log 2>/dev/null | tail -n 1' |
		tr ' ' '\n' | awk -F= -v k="$1" '$1 == k { v = $2 } END { print v + 0 }'
}
# relay_proc <pid> <field>: VmRSS / VmHWM in kB, or cpu = utime+stime in ms.
relay_proc() {
	if [ "$2" = cpu ]; then
		docker exec "$SESS" bash -c "awk '{ sub(/^.*\\) /, \"\"); print (\$12 + \$13) * 10 }' /proc/$1/stat"
	else
		docker exec "$SESS" awk -v k="$2:" '$1 == k { print $2 }' "/proc/$1/status"
	fi
}
wait_relay() { # wait_relay [generation]: until listening (and at that generation)
	local i=0
	until relay_listening && { [ -z "${1:-}" ] || docker exec "$SESS" grep -q "generation=$1" /tmp/st-relay.log 2>/dev/null; }; do
		i=$((i + 1))
		[ "$i" -gt 100 ] && return 1
		sleep 0.1
	done
}

# claude_p <prompt> [extra claude args…]: one headless run (no tmux, like
# the exec API); stdout → $TMP/last.out, wall ms → $LAST_MS.
claude_p() {
	local prompt="$1"
	shift
	local t0
	t0=$(ms_now)
	docker exec -w /home/developer/workspace "$SESS" timeout 120 claude -p "$prompt" "$@" </dev/null >"$TMP/last.out" 2>"$TMP/last.err"
	LAST_RC=$?
	LAST_MS=$(($(ms_now) - t0))
}
out_is() {
	[ "$(cat "$TMP/last.out")" = "$1" ] && return 0
	{ echo "    want: $(printf %q "$1")"; echo "    got:  $(printf %q "$(cat "$TMP/last.out")") (rc=$LAST_RC)"; sed 's/^/    stderr: /' "$TMP/last.err"; } >&2
	return 1
}
HOLA_OUT=$'Hello from the mock.\nSecond line.'
BASH_OUT=$'Tool finished.\nDone.'

# Interactive tab, as the backend creates one (`tmux new-session` via exec,
# so the CLI gets TMUX_PANE and the container env).
tab_start() { # tab_start <claude args…>
	docker exec "$SESS" tmux kill-server >/dev/null 2>&1
	docker exec "$SESS" tmux new-session -d -s tab1 -x 220 -y 50 -c /home/developer/workspace "claude $*"
	local i=0
	until docker exec "$SESS" tmux capture-pane -p -t tab1 2>/dev/null | grep -qE "for shortcuts|bypass permissions on|for agents"; do
		i=$((i + 1))
		if [ "$i" -gt 60 ]; then
			fail "interactive claude never reached its prompt"
			docker exec "$SESS" tmux capture-pane -p -t tab1 >&2
			return 1
		fi
		sleep 0.5
	done
}
# tab_turn <text>: submit a prompt, wait for the user's own Stop hook,
# LAST_MS = submit→stop as the user's hooks saw it (-1 if it never came).
tab_turn() {
	docker exec "$SESS" bash -c ': > /tmp/user-hooks.log'
	docker exec "$SESS" tmux send-keys -t tab1 "$1" Enter
	local i=0
	until docker exec "$SESS" grep -q '^stop' /tmp/user-hooks.log 2>/dev/null; do
		i=$((i + 1))
		[ "$i" -gt 300 ] && { LAST_MS=-1; return 1; }
		sleep 0.1
	done
	LAST_MS=$(docker exec "$SESS" awk '/^submit/{a=$2} /^stop/{b=$2} END{print b-a}' /tmp/user-hooks.log)
}
tab_screen() { docker exec "$SESS" tmux capture-pane -p -S -500 -t tab1; }
screen_has() { tab_screen | grep -q "$1"; }
hook_errors() { tab_screen | grep -c -i 'hook error'; }

docker network create "$NET" >/dev/null || { fail "docker network create"; exit 1; }

# ── Phase 0 ─────────────────────────────────────────────────────────────────
phase "Phase 0: compose alias"
ALIASES=$(cd "$REPO_ROOT" && JWT_SECRET=x SECRETS_ENCRYPTION_KEY=x docker compose -f docker-compose.yml config --format json 2>/dev/null |
	jq -c '.services.app.networks["sessions-net"].aliases // []')
check "app has the st-backend alias on sessions-net ($ALIASES)" grep -q '"st-backend"' <<<"$ALIASES"

# ── Phase 1 ─────────────────────────────────────────────────────────────────
phase "Phase 1: image layout and pin"
LAYOUT=$(docker run --rm --entrypoint bash "$IMAGE" -c '
	stat -c "%U:%G %a" /etc/claude-code/managed-settings.d /opt/st/hooks/session-start.sh /opt/st/hooks/relay.py
	ls -A /etc/claude-code/managed-settings.d | wc -l
	touch /etc/claude-code/managed-settings.d/x.json 2>/dev/null && echo writable || echo not-writable
	(echo x >> /opt/st/hooks/session-start.sh) 2>/dev/null && echo writable || echo not-writable
	(echo x >> /opt/st/hooks/relay.py) 2>/dev/null && echo writable || echo not-writable
	command claude --version
	python3 -IS -c "import sys; print(sys.version.split()[0])"')
check "managed dir root:root 755" [ "$(sed -n 1p <<<"$LAYOUT")" = "root:root 755" ]
check "script root:root 755" [ "$(sed -n 2p <<<"$LAYOUT")" = "root:root 755" ]
check "relay root:root 755" [ "$(sed -n 3p <<<"$LAYOUT")" = "root:root 755" ]
check "managed dir empty in the image" [ "$(sed -n 4p <<<"$LAYOUT")" = 0 ]
check "developer can't plant a managed file" [ "$(sed -n 5p <<<"$LAYOUT")" = not-writable ]
check "developer can't modify the script" [ "$(sed -n 6p <<<"$LAYOUT")" = not-writable ]
check "developer can't modify the relay" [ "$(sed -n 7p <<<"$LAYOUT")" = not-writable ]
PIN=$(grep -oP '^ARG CLAUDE_CODE_VERSION=\K\S+' "$REPO_ROOT/session-image/Dockerfile")
GOT=$(sed -n 8p <<<"$LAYOUT")
check "claude --version = '$GOT' (pin $PIN, contract floor 2.1.308)" [ "$GOT" = "$PIN (Claude Code)" ]
note "python3 for the relay: $(sed -n 9p <<<"$LAYOUT")"

start_api || exit 1

# ── Phase 2 ─────────────────────────────────────────────────────────────────
phase "Phase 2: capture off ⇒ zero requests, no relay"
receiver ok off
for variant in "no:none" "yes:none" "yes:empty"; do
	session "${variant%%:*}" "${variant##*:}" || exit 1
	runs=()
	for _ in 1 2 3; do
		claude_p hola
		runs+=("$LAST_MS")
	done
	check "[$variant] claude -p answers normally" out_is "$HOLA_OUT"
	tab_start --dangerously-skip-permissions && tab_turn "ST_SCENARIO=bash" || fail "[$variant] interactive turn"
	check "[$variant] zero requests to st-backend (-p ×3 + one interactive turn with a tool)" [ "$(count off)" = 0 ]
	check "[$variant] no relay process" [ "$(relay_count)" = 0 ]
	check "[$variant] nothing listens on 127.0.0.1:$RELAY_PORT" relay_closed
	note "capture off [$variant]: claude -p hola median $(median3 "${runs[@]}") ms"
done
BASE_HOLA=$(median3 "${runs[@]}")
runs=()
for _ in 1 2 3; do
	claude_p "ST_SCENARIO=bash"
	runs+=("$LAST_MS")
done
BASE_BASH=$(median3 "${runs[@]}")
tab_turn "ST_SCENARIO=slow:60:20"
BASE_SLOW=$LAST_MS
tab_turn "ST_SCENARIO=slow:400:5"
BASE_STREAM=$LAST_MS
docker exec "$SESS" tmux kill-server >/dev/null 2>&1
note "baseline without hooks: -p hola $BASE_HOLA ms, -p with one Bash tool $BASE_BASH ms; interactive paced 60 lines $BASE_SLOW ms, 400-line stream $BASE_STREAM ms"

# ── Phase 3 ─────────────────────────────────────────────────────────────────
phase "Phase 3: capture on, real backend"
write_hooks_file
receiver real on || exit 1
session yes file || exit 1
check "exactly one relay process" [ "$(relay_count)" = 1 ]
RELAY_HEX=$(printf '%04X' "$RELAY_PORT")
LISTEN=$(docker exec "$SESS" awk -v p=":$RELAY_HEX" '$2 ~ p"$" && $4 == "0A" { print $2 }' /proc/net/tcp /proc/net/tcp6 2>/dev/null)
check "relay listens on 127.0.0.1:$RELAY_PORT only ($LISTEN)" [ "$LISTEN" = "0100007F:$RELAY_HEX" ]
check "unreachable from another container on the network" bash -c '! docker exec "$1" node -e "
	const s = require(\"net\").connect($2, \"$3\");
	s.on(\"connect\", () => process.exit(0)); s.on(\"error\", () => process.exit(1));
	setTimeout(() => process.exit(1), 2000);"' _ "$API" "$RELAY_PORT" "$SESS"
check "the managed hooks file carries no credential" \
	bash -c '! docker exec "$1" grep -q -e ST_INGEST_TOKEN -e Authorization /etc/claude-code/managed-settings.d/conversation.json' _ "$SESS"
RELAY_PID=$(relay_pids | head -n 1)
runs=()
for _ in 1 2 3; do
	claude_p hola
	runs+=("$LAST_MS")
done
check "claude -p output unchanged with hooks" out_is "$HOLA_OUT"
ON_HOLA=$(median3 "${runs[@]}")
runs=()
for _ in 1 2 3; do
	claude_p "ST_SCENARIO=bash"
	runs+=("$LAST_MS")
done
check "tool run output unchanged with hooks" out_is "$BASH_OUT"
ON_BASH=$(median3 "${runs[@]}")
note "with hooks, backend up: -p hola $ON_HOLA ms (base $BASE_HOLA), -p with Bash $ON_BASH ms (base $BASE_BASH)"
claude_p "ST_SCENARIO=agent"
check "subagent run completes" [ "$LAST_RC" = 0 ]
claude_p "ST_SCENARIO=bashfail" --dangerously-skip-permissions
tab_start --dangerously-skip-permissions || exit 1
tab_turn "ST_SCENARIO=slow:60:20"
ON_SLOW=$LAST_MS
md_before=$(count on '.event == "MessageDisplay"')
cpu_before=$(relay_proc "$RELAY_PID" cpu)
tab_turn "ST_SCENARIO=slow:400:5"
ON_STREAM=$LAST_MS
sleep 1
cpu_after=$(relay_proc "$RELAY_PID" cpu)
md_stream=$(($(count on '.event == "MessageDisplay"') - md_before))
check "no hook error on screen" [ "$(hook_errors)" = 0 ]
docker exec "$SESS" tmux kill-server >/dev/null 2>&1
sleep 1
