#!/bin/bash
# ──────────────────────────────────────────────────────────────────────────────
# Conversation-hooks smoke test (Phase 3.0c, docs/CONVERSATION.md §10 "3.0c").
#
# Runs the REAL `claude` of the built image inside a session container set up
# the way DockerManager sets one up (hardened run flags, SESSION_ID, the
# managed-settings directory bind-mounted read-only, ST_INGEST_TOKEN only when
# capture is on), on a private Docker network where `st-backend` is a real
# network alias, exactly like `sessions-net` in docker-compose.yml.
#
# What stands in for production:
#   - the model: session-image/test/mock-anthropic.mjs (ANTHROPIC_BASE_URL),
#     a scripted Messages API — no API key, no egress, no cost;
#   - the receiver: session-image/test/st-receiver.mts, the real 3.0b ingest
#     stack (handler + service + store) with only D1 emulated; or
#     session-image/test/recorder.mjs where a misbehaving receiver is the
#     point (hang, 500, non-JSON);
#   - the hooks file: generated by the backend's own buildHooksSettings(), so
#     this test can't drift from what 3.0b writes, and written root-owned
#     (0755 dir / 0644 file) as the backend does;
#   - the emergency command: the real `conversation:disable` CLI, in another
#     process, against the same host directory.
#
# Phases:
#   0  compose: `app` carries the `st-backend` alias on sessions-net
#   1  image: empty managed dir + script, root-owned, CLI pin
#   2  capture off (no mount / token without file / empty mount): zero requests
#   3  capture on, real receiver: contract events persisted with identifiers,
#      subagents, coexistence with the user's own hooks, PermissionRequest
#      still prompts the user (a hook never decides)
#   4  receiver unreachable (DNS, refused), hung, unexpected answers: the
#      agent's result is unchanged and the cost is bounded
#   5  script and CLI faults: script ≤ 6 s in every failure mode, a failing or
#      hanging `claude --version`, the script missing
#   6  container restart and recreate: capture follows mount + env only; the
#      token never lands in the workspace
#   7  revocation (real CLI) and deactivation (file removed): ingest cut at
#      once, next session silent; hot-reload of a running session measured
#
# A markdown summary of every measurement is printed at the end and, in CI,
# appended to $GITHUB_STEP_SUMMARY.
#
# Usage: ./session-image/conversation-smoke.sh [image-tag]
# Dependencies: docker (with compose), node + backend deps (`npm ci` in
# backend/), jq.
# ──────────────────────────────────────────────────────────────────────────────
set -uo pipefail

IMAGE="${1:-shared-terminal-session}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SUF="$$"
NET="st-conv-net-$SUF"
API="st-conv-api-$SUF"
RECV="st-conv-recv-$SUF"
SESS="st-conv-sess-$SUF"
TMP="$(mktemp -d)"
WS="$TMP/ws"          # the session's workspace bind mount
WR="$TMP/wr"          # the receiver's WORKSPACE_ROOT (host side)
OUT="$TMP/out"        # raw request logs written by the stand-ins
EMPTY="$TMP/empty"    # an empty directory to mount over things
mkdir -p "$WS" "$WR" "$OUT" "$EMPTY"
chmod 777 "$WS" "$OUT"
SID="$(cat /proc/sys/kernel/random/uuid)"
TOKEN="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
API_KEY="sk-ant-api03-smoke-$(head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')"
MANAGED="$WR/.claude-managed/$SID"
FAILS=0
SUMMARY="$TMP/summary.md"
: >"$SUMMARY"

cleanup() {
	docker rm -f "$API" "$RECV" "$SESS" >/dev/null 2>&1
	docker network rm "$NET" >/dev/null 2>&1
	# Root- and uid-1000-owned files from the containers: empty the dirs
	# from a throwaway root container, then drop them.
	docker run --rm --user 0 -v "$TMP":/t --entrypoint bash "$IMAGE" \
		-c 'rm -rf /t/* /t/.[!.]* 2>/dev/null; true' >/dev/null 2>&1
	rm -rf "$TMP" 2>/dev/null
}
trap cleanup EXIT

phase() { echo; echo "── $1 ──"; echo >>"$SUMMARY"; echo "**$1**" >>"$SUMMARY"; echo >>"$SUMMARY"; }
ok() { echo "  ok: $1"; }
fail() {
	echo "  FAIL: $1" >&2
	echo "- FAIL: $1" >>"$SUMMARY"
	FAILS=$((FAILS + 1))
}
check() { # check <description> <command...>
	local what="$1"
	shift
	if "$@"; then ok "$what"; else fail "$what"; fi
}
note() { echo "  · $1"; echo "- $1" >>"$SUMMARY"; }
ms_now() { echo $(($(date +%s%N) / 1000000)); }
median3() { printf '%s\n' "$@" | sort -n | sed -n 2p; }

# Root-side view of the receiver's host directory (files there are owned by
# root, as the backend's are).
as_root() { docker run --rm --user 0 -v "$WR":/wr -v "$OUT":/out --entrypoint bash "$IMAGE" -c "$1"; }

# ── Stand-ins ───────────────────────────────────────────────────────────────
start_api() {
	docker run -d --name "$API" --network "$NET" --network-alias mock-api \
		-v "$REPO_ROOT/session-image/test":/t:ro -v "$OUT":/out \
		--entrypoint node "$IMAGE" /t/mock-anthropic.mjs 8080 /out/model-requests.jsonl >/dev/null
	wait_log "$API" "listening"
}

wait_log() { # wait_log <container> <text>
	local i=0
	until docker logs "$1" 2>&1 | grep -q "$2"; do
		i=$((i + 1))
		if [ "$i" -gt 120 ]; then
			fail "$1 never logged '$2'"
			docker logs "$1" 2>&1 | tail -20 >&2
			return 1
		fi
		sleep 0.5
	done
}

# receiver <kind> <tag>: kind = real | ok | hang | status500 | text200 |
# json200-invalid | refused | none. Every kind but `none` owns the
# `st-backend` alias; requests land in $OUT/<tag>.jsonl.
receiver() {
	docker rm -f "$RECV" >/dev/null 2>&1
	local kind="$1" tag="$2"
	case "$kind" in
	none) return 0 ;;
	refused)
		# The name resolves, nothing listens on 3001.
		docker run -d --name "$RECV" --network "$NET" --network-alias st-backend \
			--entrypoint sleep "$IMAGE" infinity >/dev/null
		return 0
		;;
	real)
		docker run -d --name "$RECV" --network "$NET" --network-alias st-backend --user 0 \
			-v "$REPO_ROOT":/repo:ro -v "$WR":/wr -v "$OUT":/out -w /repo/backend \
			-e WORKSPACE_ROOT=/wr -e ST_TEST_TOKEN="$TOKEN" -e ST_TEST_SESSION="$SID" \
			-e RAW_OUT="/out/$tag.jsonl" \
			--entrypoint node "$IMAGE" node_modules/tsx/dist/cli.mjs ../session-image/test/st-receiver.mts >/dev/null
		;;
	*)
		docker run -d --name "$RECV" --network "$NET" --network-alias st-backend --user 0 \
			-v "$REPO_ROOT/session-image/test":/t:ro -v "$OUT":/out \
			--entrypoint node "$IMAGE" /t/recorder.mjs "$kind" 3001 "/out/$tag.jsonl" >/dev/null
		;;
	esac
	wait_log "$RECV" "listening"
}

count() { # count <tag> [jq filter]: requests a stand-in received
	local f="$OUT/$1.jsonl"
	[ -f "$f" ] || { echo 0; return; }
	jq -s "map(select(${2:-true})) | length" "$f"
}

# ── Hooks file (host side, root-owned like the backend's) ──────────────────
# To a file, not a variable: `$(…)` would strip the trailing newline and the
# copy would no longer be byte-identical to what 3.0b writes.
HOOKS_FILE="$TMP/conversation.json"
(cd "$REPO_ROOT/backend" && npx tsx -e \
	'import { buildHooksSettings } from "./src/conversation/activation.ts"; process.stdout.write(buildHooksSettings(3001))') >"$HOOKS_FILE" ||
	{ fail "couldn't generate the hooks file from activation.ts"; exit 1; }
write_hooks_file() { # atomic, like writeHooksFile(): temp name the CLI ignores, then rename
	docker run --rm -i --user 0 -v "$WR":/wr --entrypoint bash "$IMAGE" -c "
		install -d -m 0755 /wr/.claude-managed /wr/.claude-managed/$SID &&
		cat > /wr/.claude-managed/$SID/conversation.json.tmp.1 &&
		chmod 0644 /wr/.claude-managed/$SID/conversation.json.tmp.1 &&
		mv /wr/.claude-managed/$SID/conversation.json.tmp.1 /wr/.claude-managed/$SID/conversation.json" <"$HOOKS_FILE"
}
remove_hooks_file() { as_root "rm -f /wr/.claude-managed/$SID/conversation.json"; }

# ── Session container ───────────────────────────────────────────────────────
# session <with-token: yes|no> <managed: file|empty|none> [extra docker args…]
# Flags mirror DockerManager.spawn(): init, all caps dropped,
# no-new-privileges, SESSION_ID always, the token only when capture is on.
session() {
	local tok="$1" managed="$2"
	shift 2
	docker rm -f "$SESS" >/dev/null 2>&1
	local args=(--init --cap-drop ALL --security-opt no-new-privileges --pids-limit 512
		--network "$NET" -e SESSION_ID="$SID" -e SESSION_NAME=smoke
		-e ANTHROPIC_BASE_URL=http://mock-api:8080 -e ANTHROPIC_API_KEY="$API_KEY"
		-e CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1
		-v "$WS":/home/developer/workspace)
	[ "$tok" = yes ] && args+=(-e ST_INGEST_TOKEN="$TOKEN")
	case "$managed" in
	file) args+=(-v "$MANAGED":/etc/claude-code/managed-settings.d:ro) ;;
	empty) args+=(-v "$EMPTY":/etc/claude-code/managed-settings.d:ro) ;;
	esac
	docker run -d --name "$SESS" "${args[@]}" "$@" "$IMAGE" >/dev/null || {
		fail "docker run of the session container failed"
		return 1
	}
	wait_log "$SESS" "container ready" || return 1
	seed_claude_state
}

# Interactive-mode prerequisites the first launch would otherwise ask for
# (onboarding, API-key approval, workspace trust, bypass-mode warning), plus
# the user's OWN hooks — a command UserPromptSubmit/Stop pair writing to
# /tmp/user-hooks.log — so every phase also proves managed hooks coexist with
# them. Written through the ~/.claude* symlinks into the workspace.
seed_claude_state() {
	docker exec -i -e K="${API_KEY: -20}" "$SESS" bash -c '
		set -e
		f=~/.claude.json; [ -s "$f" ] || echo "{}" > "$f"
		jq --arg k "$K" ". + {hasCompletedOnboarding: true, theme: \"dark\",
			customApiKeyResponses: {approved: [\$k], rejected: []},
			projects: {\"/home/developer/workspace\": {hasTrustDialogAccepted: true, hasCompletedProjectOnboarding: true}}}" "$f" > /tmp/cj
		cat /tmp/cj > "$f"
		mkdir -p ~/.claude
		cat > ~/.claude/settings.json <<"EOF"
{
  "skipDangerousModePermissionPrompt": true,
  "hooks": {
    "UserPromptSubmit": [{ "hooks": [{ "type": "command", "command": "echo submit $(date +%s%3N) >> /tmp/user-hooks.log" }] }],
    "Stop": [{ "hooks": [{ "type": "command", "command": "echo stop $(date +%s%3N) >> /tmp/user-hooks.log" }] }]
  }
}
EOF'
}

# claude_p <tag-for-timing> <prompt> [extra claude args…]: one headless run
# (no tmux, like the exec API); stdout → $TMP/last.out, wall ms → $LAST_MS.
claude_p() {
	local prompt="$1"
	shift
	local t0
	t0=$(ms_now)
	docker exec -w /home/developer/workspace "$SESS" timeout 120 claude -p "$prompt" "$@" </dev/null >"$TMP/last.out" 2>"$TMP/last.err"
	LAST_RC=$?
	LAST_MS=$(($(ms_now) - t0))
}
out_is() { [ "$(cat "$TMP/last.out")" = "$1" ]; }
HOLA_OUT=$'Hello from the mock.\nSecond line.'
BASH_OUT=$'Tool finished.\nDone.'

# Interactive tab, as the backend creates one (`tmux new-session` via exec,
# so the CLI gets TMUX_PANE and the container env).
tab_start() { # tab_start <claude args…>
	docker exec "$SESS" tmux kill-server >/dev/null 2>&1
	docker exec "$SESS" tmux new-session -d -s tab1 -x 220 -y 50 "claude $*"
	local i=0
	until docker exec "$SESS" tmux capture-pane -p -t tab1 2>/dev/null | grep -qE "for shortcuts|bypass permissions on|for agents"; do
		i=$((i + 1))
		if [ "$i" -gt 60 ]; then
			fail "interactive claude never reached its prompt"
			docker exec "$SESS" tmux capture-pane -p -t tab1 >&2
			return 1
		fi
		sleep 0.5
	done
}
# tab_turn <text>: submit a prompt, wait for the user's own Stop hook,
# LAST_MS = submit→stop as the user's hooks saw it.
tab_turn() {
	docker exec "$SESS" bash -c ': > /tmp/user-hooks.log'
	docker exec "$SESS" tmux send-keys -t tab1 "$1" Enter
	local i=0
	until docker exec "$SESS" grep -q '^stop' /tmp/user-hooks.log 2>/dev/null; do
		i=$((i + 1))
		[ "$i" -gt 300 ] && { LAST_MS=-1; return 1; }
		sleep 0.1
	done
	LAST_MS=$(docker exec "$SESS" awk '/^submit/{a=$2} /^stop/{b=$2} END{print b-a}' /tmp/user-hooks.log)
}
tab_screen() { docker exec "$SESS" tmux capture-pane -p -S -200 -t tab1; }
screen_has() { tab_screen | grep -q "$1"; }

docker network create "$NET" >/dev/null || { fail "docker network create"; exit 1; }

# ── Phase 0 ─────────────────────────────────────────────────────────────────
phase "Phase 0: compose alias"
ALIASES=$(cd "$REPO_ROOT" && JWT_SECRET=x SECRETS_ENCRYPTION_KEY=x docker compose -f docker-compose.yml config --format json 2>/dev/null |
	jq -c '.services.app.networks["sessions-net"].aliases // []')
check "app has the st-backend alias on sessions-net ($ALIASES)" grep -q '"st-backend"' <<<"$ALIASES"

# ── Phase 1 ─────────────────────────────────────────────────────────────────
phase "Phase 1: image layout and pin"
LAYOUT=$(docker run --rm --entrypoint bash "$IMAGE" -c '
	stat -c "%U:%G %a" /etc/claude-code/managed-settings.d /opt/st/hooks/session-start.sh
	ls -A /etc/claude-code/managed-settings.d | wc -l
	touch /etc/claude-code/managed-settings.d/x.json 2>/dev/null && echo writable || echo not-writable
	echo x >> /opt/st/hooks/session-start.sh 2>/dev/null && echo writable || echo not-writable
	command claude --version')
check "managed dir root:root 755" grep -qx "root:root 755" <<<"$(sed -n 1p <<<"$LAYOUT")"
check "script root:root 755" grep -qx "root:root 755" <<<"$(sed -n 2p <<<"$LAYOUT")"
check "managed dir empty in the image" [ "$(sed -n 3p <<<"$LAYOUT")" = 0 ]
check "developer can't plant a managed file" [ "$(sed -n 4p <<<"$LAYOUT")" = not-writable ]
check "developer can't modify the script" [ "$(sed -n 5p <<<"$LAYOUT")" = not-writable ]
PIN=$(grep -oP '^ARG CLAUDE_CODE_VERSION=\K\S+' "$REPO_ROOT/session-image/Dockerfile")
GOT=$(sed -n 6p <<<"$LAYOUT")
check "claude --version = '$GOT' (pin $PIN, contract floor 2.1.308)" [ "$GOT" = "$PIN (Claude Code)" ]

start_api || exit 1

# ── Phase 2 ─────────────────────────────────────────────────────────────────
phase "Phase 2: capture off ⇒ zero requests"
receiver ok off
for variant in "no:none" "yes:none" "yes:empty"; do
	session "${variant%%:*}" "${variant##*:}" || exit 1
	runs=()
	for _ in 1 2 3; do
		claude_p hola
		runs+=("$LAST_MS")
	done
	check "[$variant] claude -p answers normally" out_is "$HOLA_OUT"
	tab_start --dangerously-skip-permissions && tab_turn "ST_SCENARIO=bash" || fail "[$variant] interactive turn"
	check "[$variant] zero requests to st-backend (-p ×3 + one interactive turn with a tool)" [ "$(count off)" = 0 ]
	note "capture off [$variant]: claude -p hola median $(median3 "${runs[@]}") ms"
done
BASE_HOLA=$(median3 "${runs[@]}")
runs=()
for _ in 1 2 3; do
	claude_p "ST_SCENARIO=bash"
	runs+=("$LAST_MS")
done
BASE_BASH=$(median3 "${runs[@]}")
note "baseline without hooks: -p hola $BASE_HOLA ms, -p with one Bash tool $BASE_BASH ms"

# ── Phase 3 ─────────────────────────────────────────────────────────────────
phase "Phase 3: capture on, real receiver"
write_hooks_file
receiver real on || exit 1
session yes file || exit 1
runs=()
for _ in 1 2 3; do
	claude_p hola
	runs+=("$LAST_MS")
done
check "claude -p output unchanged with hooks" out_is "$HOLA_OUT"
ON_HOLA=$(median3 "${runs[@]}")
runs=()
for _ in 1 2 3; do
	claude_p "ST_SCENARIO=bash"
	runs+=("$LAST_MS")
done
check "tool run output unchanged with hooks" out_is "$BASH_OUT"
ON_BASH=$(median3 "${runs[@]}")
note "with hooks, receiver up: -p hola $ON_HOLA ms (base $BASE_HOLA), -p with Bash $ON_BASH ms (base $BASE_BASH)"
claude_p "ST_SCENARIO=agent"
claude_p "ST_SCENARIO=bashfail"
tab_start --dangerously-skip-permissions || exit 1
tab_turn "ST_SCENARIO=slow:60:20"
ON_SLOW=$LAST_MS
docker exec "$SESS" tmux kill-server >/dev/null 2>&1
sleep 1

# Identifiers on the wire.
check "every request carries Authorization: Bearer <token>" \
	[ "$(count on ".authorization != \"Bearer $TOKEN\"")" = 0 ]
check "every request carries X-ST-Session = SESSION_ID" [ "$(count on ".session != \"$SID\"")" = 0 ]
check "headless runs send an empty pane, the tab sends its %N" \
	[ "$(count on '(.pane // "") != "" and (.pane | test("^%[0-9]+$") | not)')" = 0 ]
check "the tab's events carry its pane" [ "$(count on '(.pane // "") | test("^%[0-9]+$")')" -gt 0 ]
RESP="$OUT/on.responses.jsonl"
check "every answer was 204" [ "$(jq -s 'map(select(.status != 204)) | length' "$RESP")" = 0 ]
note "receiver answers: $(jq -s 'length' "$RESP") × 204, max $(jq -s 'map(.ms) | max' "$RESP") ms, p50 $(jq -s 'map(.ms) | sort | .[length/2|floor]' "$RESP") ms"
check "nothing rejected by the receiver" \
	[ "$(jq -s 'map(select(.outcome.accepted == false)) | length' "$OUT/on.outcomes.jsonl")" = 0 ]

# What production would have persisted.
EVENTS=$(as_root "cat /wr/.conversations/$SID/*.events.jsonl")
HOLA_CID=$(jq -r 'select(.event == "UserPromptSubmit" and .body.prompt == "hola") | .body.session_id' "$OUT/on.jsonl" | head -n 1)
HOLA_EVS=$(as_root "jq -r .ev /wr/.conversations/$SID/$HOLA_CID.events.jsonl" | tr '\n' ' ')
for ev in session_start user_prompt assistant_delta turn_end session_end; do
	check "-p hola persisted $ev (cid = the CLI's session_id)" grep -qw "$ev" <<<"$HOLA_EVS"
done
SS=$(as_root "jq -c 'select(.ev == \"session_start\") | .data' /wr/.conversations/$SID/$HOLA_CID.events.jsonl")
check "session_start.claude_version = 2.1.308 (from the script)" grep -q '"claude_version":"2.1.308 (Claude Code)"' <<<"$SS"
check "session_start.argv_flags = [\"-p\"] (allowlist)" grep -q '"argv_flags":\["-p"\]' <<<"$SS"
check "assistant_delta final=true carries the full text" \
	grep -q '"final":true' <<<"$(as_root "jq -c 'select(.ev == \"assistant_delta\") | .data' /wr/.conversations/$SID/$HOLA_CID.events.jsonl")"
PAIRS=$(jq -cs '[.[] | select(.event == "PreToolUse" or .event == "PostToolUse" or .event == "PostToolUseFailure") | .body.tool_use_id] | group_by(.) | map(length) | unique' "$OUT/on.jsonl")
check "every tool_use_id has its start and its end ($PAIRS)" [ "$PAIRS" = "[2]" ]
check "a failing tool is tool_failed" grep -q '"ev":"tool_failed"' <<<"$EVENTS"
AGENT=$(jq -s '[.[] | select(.event == "SubagentStart" or .event == "SubagentStop") | .body.agent_id] | unique | length' "$OUT/on.jsonl")
check "subagent: SubagentStart/Stop share one agent_id" [ "$AGENT" = 1 ]
check "subagent persisted as agent_start/agent_end" bash -c 'grep -q "\"ev\":\"agent_start\"" <<<"$1" && grep -q "\"ev\":\"agent_end\"" <<<"$1"' _ "$EVENTS"
TURN_IDS=$(jq -s --arg c "$HOLA_CID" '[.[] | select(.body.session_id == $c and (.event == "UserPromptSubmit" or .event == "MessageDisplay" or .event == "Stop")) | .body.prompt_id] | unique | length' "$OUT/on.jsonl")
check "user_prompt, assistant_delta and turn_end of one turn share its prompt_id" [ "$TURN_IDS" = 1 ]
MD=$(count on '.event == "MessageDisplay" and (.pane // "") != ""')
note "interactive paced stream (60 lines over ~1.2 s): $MD MessageDisplay batches, turn $ON_SLOW ms"

# The user's own hooks ran alongside the managed ones.
check "user's own UserPromptSubmit/Stop hooks still ran" docker exec "$SESS" grep -q '^stop' /tmp/user-hooks.log
# disableAllHooks in USER settings can't switch managed hooks off (documented
# CLI behaviour) — measured, since it decides who can stop capture.
before=$(count on)
claude_p hola --settings '{"disableAllHooks": true}'
after=$(count on)
note "user-level disableAllHooks: true ⇒ $((after - before)) managed requests still sent (managed hooks are not user-disableable)"

# PermissionRequest: the hook answers 204 and the user is still asked.
session yes file || exit 1
tab_start --permission-mode default || exit 1
before=$(count on '.event == "PermissionRequest"')
docker exec "$SESS" tmux send-keys -t tab1 "ST_SCENARIO=bashwrite" Enter
i=0
until tab_screen | grep -q "Do you want to proceed"; do
	i=$((i + 1))
	[ "$i" -gt 60 ] && break
	sleep 0.5
done
check "permission dialog shown to the user (the hook did not decide)" screen_has "Do you want to proceed"
check "PermissionRequest reached the receiver" [ "$(count on '.event == "PermissionRequest"')" -gt "$before" ]
docker exec "$SESS" tmux send-keys -t tab1 Escape
docker exec "$SESS" tmux kill-server >/dev/null 2>&1

# ── Phase 4 ─────────────────────────────────────────────────────────────────
phase "Phase 4: receiver unreachable, hung or answering oddly"
session yes file || exit 1
for kind in none refused hang status500 text200 json200-invalid; do
	receiver "$kind" "rx-$kind"
	claude_p hola
	h_ms=$LAST_MS
	check "[$kind] -p hola: exit 0, output unchanged" bash -c '[ "$1" = 0 ] && [ "$(cat "$2")" = "$3" ]' _ "$LAST_RC" "$TMP/last.out" "$HOLA_OUT"
	claude_p "ST_SCENARIO=bash"
	b_ms=$LAST_MS
	check "[$kind] tool run: output unchanged" out_is "$BASH_OUT"
	n=$(count "rx-$kind" '.event != "SessionStart"')
	note "receiver $kind: -p hola $h_ms ms, -p with Bash $b_ms ms (bases $BASE_HOLA / $BASE_BASH; http hook requests received: $n; stderr lines of the Bash run: $(grep -c . "$TMP/last.err"))"
	if [ "$kind" = hang ]; then
		# Contract §10: ≤ base + 1 s × events. The Bash run has 5 blocking
		# http hooks (UserPromptSubmit, PreToolUse, PostToolUse, Stop,
		# SessionEnd) + MessageDisplay; allow 1.5 s of slack for docker exec.
		check "[hang] -p with Bash ≤ base + 1 s × 6 events + 1.5 s" [ "$b_ms" -le $((BASE_BASH + 6000 + 1500)) ]
	else
		check "[$kind] -p with Bash within base + 1.5 s" [ "$b_ms" -le $((BASE_BASH + 1500)) ]
	fi
done
tab_start --dangerously-skip-permissions && tab_turn "ST_SCENARIO=bash"
SCREEN=$(tab_screen)
note "interactive, receiver answering non-JSON: the tab shows $(grep -c 'hook error' <<<"$SCREEN") 'hook error' line(s); see PR notes"
check "hook errors never reach the model" [ "$(grep -c -e 'st-backend' -e 'hook error' "$OUT/model-requests.jsonl")" = 0 ]
docker exec "$SESS" tmux kill-server >/dev/null 2>&1

# ── Phase 5 ─────────────────────────────────────────────────────────────────
phase "Phase 5: script and CLI faults"
SS_IN='{"session_id":"5b8f3d7e-0c43-4f7a-9d61-2a1e0f9b7c55","hook_event_name":"SessionStart","cwd":"/w","source":"startup"}'
docker exec "$SESS" bash -c 'mkdir -p /tmp/hangbin && printf "#!/bin/bash\nexec sleep 30\n" > /tmp/hangbin/claude && chmod +x /tmp/hangbin/claude'
script_run() { # script_run <PATH prefix or ""> → ms
	local t0
	t0=$(ms_now)
	docker exec -i -e PFX="$1" "$SESS" bash -c 'PATH="${PFX:+$PFX:}$PATH" /opt/st/hooks/session-start.sh' <<<"$SS_IN" >"$TMP/ss.out" 2>&1
	echo $(($(ms_now) - t0))
}
receiver none ss-none
t=$(script_run "")
check "script, st-backend unresolved: $t ms ≤ 6000, silent" bash -c '[ "$1" -le 6000 ] && [ ! -s "$2" ]' _ "$t" "$TMP/ss.out"
receiver hang ss-hang
t=$(script_run "")
check "script, receiver accepts and never answers: $t ms ≤ 6000" [ "$t" -le 6000 ]
receiver ok ss-ok
t=$(script_run /tmp/hangbin)
check "script, claude --version hangs: $t ms ≤ 6000, event still sent with claude_version null" \
	bash -c '[ "$1" -le 6000 ] && [ "$(jq -r ".body.st.claude_version" "$2" | tail -n 1)" = null ]' _ "$t" "$OUT/ss-ok.jsonl"
receiver hang ss-hang2
t=$(script_run /tmp/hangbin)
check "script, claude hangs AND receiver hangs: $t ms ≤ 6000" [ "$t" -le 6000 ]
sleep 0.5
check "no survivor of the hung children" \
	bash -c '! docker exec "$1" bash -c "for f in /proc/[0-9]*/cmdline; do tr \"\\0\" \" \" < \$f 2>/dev/null; echo; done" | grep -q "^sleep 30"' _ "$SESS"
note "script timings: unresolved / hung receiver / hung claude --version / both — all ≤ 6 s (values above)"

# `claude --version` broken must not stop claude itself.
receiver real faults || exit 1
docker exec "$SESS" bash -c 'mkdir -p /tmp/wrap && printf "#!/bin/bash\n[ \"\$1\" = --version ] && exit 1\nexec /home/developer/.npm-global/bin/claude \"\$@\"\n" > /tmp/wrap/claude && chmod +x /tmp/wrap/claude'
t0=$(ms_now)
docker exec -w /home/developer/workspace "$SESS" bash -c 'PATH=/tmp/wrap:$PATH timeout 120 claude -p hola </dev/null' >"$TMP/last.out" 2>/dev/null
check "claude --version failing: claude -p still answers" out_is "$HOLA_OUT"
sleep 1
check "…and session_start arrives with claude_version null" \
	[ "$(jq -r 'select(.event == "SessionStart") | .body.st.claude_version' "$OUT/faults.jsonl" | tail -n 1)" = null ]
docker exec "$SESS" bash -c 'printf "#!/bin/bash\n[ \"\$1\" = --version ] && exec sleep 30\nexec /home/developer/.npm-global/bin/claude \"\$@\"\n" > /tmp/wrap/claude'
before=$(count faults '.event == "SessionStart"')
t0=$(ms_now)
docker exec -w /home/developer/workspace "$SESS" bash -c 'PATH=/tmp/wrap:$PATH timeout 120 claude -p hola </dev/null' >"$TMP/last.out" 2>/dev/null
HANG_MS=$(($(ms_now) - t0))
check "claude --version hanging: claude -p still answers ($HANG_MS ms)" out_is "$HOLA_OUT"
sleep 4
note "claude --version hanging under -p: session_start delivered $(($(count faults '.event == "SessionStart"') - before)) time(s) (the CLI cancels async hooks still running at -p teardown)"
# Script missing (an image without it, or a broken one): the CLI keeps working.
session yes file -v "$EMPTY":/opt/st/hooks:ro || exit 1
claude_p hola
check "script missing: claude -p still answers" out_is "$HOLA_OUT"
note "script missing: claude -p stderr lines: $(grep -c . "$TMP/last.err")"

# ── Phase 6 ─────────────────────────────────────────────────────────────────
phase "Phase 6: restart and recreate"
receiver real restart || exit 1
session yes file || exit 1
docker restart "$SESS" >/dev/null
i=0
until docker exec "$SESS" test -e /tmp/.st-ready 2>/dev/null; do
	i=$((i + 1))
	[ "$i" -gt 120 ] && { fail "container never ready after restart"; break; }
	sleep 0.5
done
claude_p hola
sleep 1
check "after docker restart (same env + mounts): events accepted" \
	[ "$(jq -s 'map(select(.step == "ingest" and .outcome.accepted == true)) | length' "$OUT/restart.outcomes.jsonl")" -ge 4 ]
receiver ok recreate-off
session no none || exit 1
claude_p hola
tab_start --dangerously-skip-permissions && tab_turn hello
check "recreated without mount/token on the same workspace: zero requests" [ "$(count recreate-off)" = 0 ]
docker exec "$SESS" tmux kill-server >/dev/null 2>&1
check "the ingest token is nowhere in the workspace" \
	bash -c '! docker exec "$1" grep -rqs "$2" /home/developer/workspace' _ "$SESS" "$TOKEN"
receiver ok recreate-on
session yes file || exit 1
claude_p hola
check "recreated with mount + token: emits again" [ "$(count recreate-on)" -ge 4 ]

# ── Phase 7 ─────────────────────────────────────────────────────────────────
phase "Phase 7: revocation and deactivation"
# 7a — deactivation = the hooks file removed (API disable path).
receiver ok deact
session yes file || exit 1
tab_start --dangerously-skip-permissions || exit 1
tab_turn hello
remove_hooks_file
sleep 3
before=$(count deact)
tab_turn "hello again"
RUNNING_AFTER_RM=$(($(count deact) - before))
claude_p hola
NEW_AFTER_RM=$(($(count deact) - before - RUNNING_AFTER_RM))
check "file removed ⇒ the next session emits nothing" [ "$NEW_AFTER_RM" = 0 ]
note "hot reload, file removed under a running interactive session: $RUNNING_AFTER_RM request(s) on its next turn ($([ "$RUNNING_AFTER_RM" = 0 ] && echo 'stops emitting without restart' || echo 'keeps emitting until restart'))"
write_hooks_file
sleep 3
before=$(count deact)
tab_turn "and back"
note "hot reload, file re-added under the same running session: $(($(count deact) - before)) request(s) on its next turn"
docker exec "$SESS" tmux kill-server >/dev/null 2>&1

# 7b — revocation with the real emergency CLI in another process.
receiver real revoke || exit 1
session yes file || exit 1
tab_start --dangerously-skip-permissions || exit 1
tab_turn hello
accepted_before=$(jq -s 'map(select(.step == "ingest" and .outcome.accepted == true)) | length' "$OUT/revoke.outcomes.jsonl")
STUB='globalThis.fetch = async () => new Response(JSON.stringify({ success: true, errors: [], result: [{ results: [], success: true, meta: {} }] }), { status: 200, headers: { "content-type": "application/json" } });'
CLI_OUT=$(docker run --rm --user 0 -v "$REPO_ROOT":/repo:ro -v "$WR":/wr -w /repo/backend \
	-e WORKSPACE_ROOT=/wr -e CONVERSATION_ENABLED=true -e CLOUDFLARE_ACCOUNT_ID=x -e CLOUDFLARE_API_TOKEN=x -e D1_DATABASE_ID=x \
	-e NODE_OPTIONS="--import data:text/javascript,$(node -e 'process.stdout.write(encodeURIComponent(process.argv[1]))' "$STUB")" \
	--entrypoint node "$IMAGE" node_modules/tsx/dist/cli.mjs src/conversation/cli.ts disable "$SID" 2>&1)
check "conversation:disable printed 'revoked $SID'" grep -q "revoked $SID" <<<"$CLI_OUT"
check "REVOKED marker written" as_root "test -f /wr/.conversations/$SID/REVOKED"
check "hooks file removed by the command" as_root "test ! -e /wr/.claude-managed/$SID/conversation.json"
tab_turn "after revoke"
sleep 1
accepted_after=$(jq -s 'map(select(.step == "ingest" and .outcome.accepted == true)) | length' "$OUT/revoke.outcomes.jsonl")
revoked=$(jq -s 'map(select(.outcome.reason == "revoked")) | length' "$OUT/revoke.outcomes.jsonl")
check "nothing accepted after the command returned" [ "$accepted_after" = "$accepted_before" ]
note "revocation: running session's next turn → $revoked request(s) rejected as revoked (0 means the CLI had already stopped emitting)"
claude_p hola
check "after revocation a new session sends nothing" \
	[ "$(jq -s 'map(select(.event == "UserPromptSubmit" and .body.prompt == "hola")) | length' "$OUT/revoke.jsonl")" = 0 ]
docker exec "$SESS" tmux kill-server >/dev/null 2>&1

echo
echo "── Summary ──"
cat "$SUMMARY"
[ -n "${GITHUB_STEP_SUMMARY:-}" ] && { echo "## Conversation hooks smoke"; cat "$SUMMARY"; } >>"$GITHUB_STEP_SUMMARY"
echo
if [ "$FAILS" -eq 0 ]; then
	echo "CONVERSATION SMOKE TEST PASSED"
else
	echo "CONVERSATION SMOKE TEST FAILED: $FAILS assertion(s)" >&2
	exit 1
fi
